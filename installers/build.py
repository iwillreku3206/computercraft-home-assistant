#!/usr/bin/env python3
"""Generate the self-contained, wget-ready installers in dist/.

Run from anywhere:

    python3 installers/build.py
    python3 installers/build.py --check
    python3 installers/build.py client switch

The generated files do not need this repository: they embed every source file
and only download Basalt itself (once) on the ComputerCraft computer.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DIST_DIR = ROOT / "dist"
VERSION = (ROOT / "version.txt").read_text(encoding="utf-8").strip()
CHANNEL_CHOICES = ("stable", "nightly")

BASALT_VERSION = "basalt-1.7.0.lua"
BASALT_URL = (
    "https://raw.githubusercontent.com/Pyroxenium/Basalt/master/docs/versions/"
    + BASALT_VERSION
)
BASALT_FALLBACK = (
    "https://raw.githubusercontent.com/Pyroxenium/Basalt/refs/heads/master/"
    "docs/versions/basalt-1.7.0.lua"
)

TARGETS: dict[str, dict[str, object]] = {
    "client": {
        "run_command": "ha",
        "files": {
            "/ha.lua": "main/app.lua",
            "/ha/lib/ha.lua": "shared/ha.lua",
            "/ha/main/widget_shell.lua": "main/widget_shell.lua",
            "/ha/lib/updater.lua": "shared/updater.lua",
            "/ha/widgets/switch.lua": "switch/widget.lua",
            "/ha/widgets/dimmer.lua": "dimmer/widget.lua",
            "/ha/widgets/group_slider.lua": "group/widget.lua",
        },
    },
    "switch": {
        "run_command": "switch",
        "files": {
            "/switch.lua": "switch/app.lua",
            "/ha/lib/ha.lua": "shared/ha.lua",
            "/ha/lib/device_app.lua": "shared/device_app.lua",
            "/ha/lib/updater.lua": "shared/updater.lua",
            "/ha/widgets/switch.lua": "switch/widget.lua",
        },
    },
    "dimmer": {
        "run_command": "dimmer",
        "files": {
            "/dimmer.lua": "dimmer/app.lua",
            "/ha/lib/ha.lua": "shared/ha.lua",
            "/ha/lib/device_app.lua": "shared/device_app.lua",
            "/ha/lib/updater.lua": "shared/updater.lua",
            "/ha/widgets/dimmer.lua": "dimmer/widget.lua",
        },
    },
}

# "all" is the union; the client entry is included so a single computer can be
# used for a quick test, while the normal setup uses separate installers.
_all_files: dict[str, str] = {}
for _name in ("client", "switch", "dimmer"):
    _all_files.update(TARGETS[_name]["files"])  # type: ignore[arg-type]
TARGETS["all"] = {"run_command": "ha   (client), switch, dimmer", "files": _all_files}

INSTALLER_TEMPLATE = """-- Generated by installers/build.py. Target: @@TARGET@@
-- This file embeds all project sources and can be run directly with wget:
--   wget run <url-to-this-file>
local TARGET = @@TARGET_QUOTED@@
local BASALT_VERSION = @@BASALT_VERSION_QUOTED@@
local BASALT_URLS = {
  @@BASALT_URL_QUOTED@@,
  @@BASALT_FALLBACK_QUOTED@@,
}
local RUN_COMMAND = @@RUN_COMMAND_QUOTED@@

local files = {
@@FILES@@
}

local function ensureDir(path)
  if path == "" then
    return true
  end
  if fs.exists(path) then
    return true
  end
  local parent = path:match("^(.*)/[^/]+$")
  if parent and parent ~= "" and parent ~= path then
    ensureDir(parent)
  end
  local ok = pcall(fs.makeDir, path)
  return ok or fs.exists(path)
end

local function readFile(path)
  if not fs.exists(path) then
    return nil
  end
  local handle = fs.open(path, "r")
  if not handle then
    return nil
  end
  local data = handle.readAll()
  handle.close()
  return data
end

local function writeFile(path, data)
  ensureDir(path:match("^(.*)/[^/]+$") or "")
  local handle = fs.open(path, "w")
  if not handle then
    return false
  end
  handle.write(data)
  handle.close()
  return true
end

local function download(url)
  if not http then
    return nil
  end
  local ok, response = pcall(http.get, url)
  if not ok or not response then
    return nil
  end
  local data = response.readAll()
  response.close()
  if not data or #data < 10000 then
    return nil
  end
  return data
end

local function ensureBasalt()
  local existing = readFile("/basalt-ha.lua") or ""
  if existing:find("1.7.0", 1, true) then
    print("Basalt 1.7.0 already installed (/basalt-ha.lua)")
    return true
  end
  for _, url in ipairs(BASALT_URLS) do
    print("Downloading Basalt 1.7.0: " .. url)
    local data = download(url)
    if data and data:find("1.7.0", 1, true) then
      if not writeFile("/basalt-ha.lua", data) then
        print("Could not write /basalt-ha.lua")
        return false
      end
      print("Basalt installed.")
      return true
    elseif data then
      print("Downloaded file is not Basalt 1.7.0; ignoring it.")
    end
  end
  local fallback = readFile("/basalt.lua") or ""
  if fallback:find("1.7.0", 1, true) then
    print("Download failed; copying the compatible /basalt.lua.")
    return writeFile("/basalt-ha.lua", fallback)
  end
  print("Could not download Basalt 1.7.0.")
  print("Check that HTTP is enabled, or install it manually:")
  print(BASALT_URLS[1])
  print("Save it as /basalt-ha.lua and run this installer again.")
  return false
end

print("Home Assistant installer (" .. TARGET .. ")")
for path, content in pairs(files) do
  local existing = readFile(path)
  if existing == content then
    print("unchanged " .. path)
  elseif writeFile(path, content) then
    print("installed " .. path)
  else
    print("FAILED " .. path)
    return
  end
end

if not ensureBasalt() then
  return
end

-- Basalt 1.7.0's minified Slider has two bugs: draw uses a position local
-- that the minifier dropped, and click/drag compares absolute mouse
-- coordinates against relative positions. Fix both in our private copy.
local function patchBasalt()
  local path = "/basalt-ha.lua"
  local data = readFile(path)
  if not data then return end
  local changed = false

  local drawNeedle = 'addDraw("slider",function()local a_a,b_a=__a:getSize()'
  local drawFix = "local obx,oby=__a:getPosition()"
  if not data:find(drawFix, 1, true) then
    local start = data:find(drawNeedle, 1, true)
    if start then
      data = data:sub(1, start - 1) .. drawNeedle .. drawFix .. data:sub(start + #drawNeedle)
      changed = true
    else
      print("WARNING: could not apply the Basalt slider draw patch.")
    end
  end

  local mouseNeedle = 'local function cd(__a,a_a,b_a,c_a)local d_a,_aa=__a:getPosition()local aaa,baa=__a:getSize()'
  local mouseFix = 'local function cd(__a,a_a,b_a,c_a)local d_a,_aa=__a:getAbsolutePosition()local aaa,baa=__a:getSize()'
  if not data:find(mouseFix, 1, true) then
    local start = data:find(mouseNeedle, 1, true)
    if start then
      data = data:sub(1, start - 1) .. mouseFix .. data:sub(start + #mouseNeedle)
      changed = true
    else
      print("WARNING: could not apply the Basalt slider mouse patch.")
    end
  end

  if changed and writeFile(path, data) then
    print("Applied Basalt 1.7.0 slider fixes.")
  end
end

patchBasalt()
print("")
print("Done. Run: " .. RUN_COMMAND)
"""


def lua_quote(value: str) -> str:
    """Quote a short string for generated Lua source."""
    escaped = (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\t", "\\t")
    )
    return f'"{escaped}"'


def long_string(content: str) -> str:
    """Wrap source in a Lua long bracket that cannot terminate early."""
    if not content.endswith("\n"):
        content += "\n"
    level = 0
    while "]" + "=" * level + "]" in content:
        level += 1
    equals = "=" * level
    return f"[{equals}[{content}]{equals}]"


def valid_version(value: str) -> bool:
    return bool(re.fullmatch(r"\d+(?:\.\d+){1,3}", value))


def render(name: str, version: str = VERSION, channel: str = "stable") -> tuple[str, str]:
    target = TARGETS[name]
    files: dict[str, str] = target["files"]  # type: ignore[assignment]

    contents: dict[str, str] = {}
    for install_path, source_path in files.items():
        path = ROOT / source_path
        if not path.is_file():
            raise SystemExit(f"missing source {source_path}")
        contents[install_path] = path.read_text(encoding="utf-8")

    # Generated metadata used by the updater. It is written by the installer
    # alongside the program files.
    if not valid_version(version):
        raise SystemExit("version must look like 1.2.3 or 1.2.3.4")
    contents["/ha/version"] = version + "\n"
    contents["/ha/channel"] = channel + "\n"

    entries: list[str] = []
    for install_path in sorted(contents):
        source = contents[install_path]
        entries.append(f"  [{lua_quote(install_path)}] = {long_string(source)},")

    output_name = f"install-{name}.lua"
    script = (
        INSTALLER_TEMPLATE.replace("@@TARGET@@", name)
        .replace("@@INSTALLER_NAME@@", output_name)
        .replace("@@TARGET_QUOTED@@", lua_quote(name))
        .replace("@@BASALT_VERSION_QUOTED@@", lua_quote(BASALT_VERSION))
        .replace("@@BASALT_URL_QUOTED@@", lua_quote(BASALT_URL))
        .replace("@@BASALT_FALLBACK_QUOTED@@", lua_quote(BASALT_FALLBACK))
        .replace("@@RUN_COMMAND_QUOTED@@", lua_quote(str(target["run_command"])))
        .replace("@@FILES@@", "\n".join(entries))
    )
    return output_name, script


def selected_targets(requested: list[str]) -> list[str]:
    return requested or list(TARGETS)


def check_names(
    names: list[str], version: str = VERSION, channel: str = "stable"
) -> int:
    stale: list[str] = []
    for name in names:
        output_name, script = render(name, version, channel)
        path = DIST_DIR / output_name
        if not path.exists():
            stale.append(f"missing {path.relative_to(ROOT)}")
            continue
        existing = path.read_text(encoding="utf-8")
        if existing != script:
            stale.append(f"stale {path.relative_to(ROOT)}")
    if stale:
        for line in stale:
            print(line, file=sys.stderr)
        print("run `make build` or `python3 installers/build.py`", file=sys.stderr)
        return 1
    print("installers are up to date")
    return 0


def build(names: list[str], version: str = VERSION, channel: str = "stable") -> int:
    DIST_DIR.mkdir(parents=True, exist_ok=True)
    for name in names:
        output_name, script = render(name, version, channel)
        path = DIST_DIR / output_name
        with path.open("w", encoding="utf-8", newline="\n") as handle:
            handle.write(script)
        print(f"wrote {path.relative_to(ROOT)} ({len(script.encode('utf-8'))} bytes)")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate self-contained Home Assistant installers."
    )
    parser.add_argument(
        "targets",
        nargs="*",
        metavar="TARGET",
        help="targets to process (client, switch, dimmer, all); default is every target",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify that dist/install-*.lua is current instead of writing",
    )
    parser.add_argument(
        "--version",
        default=VERSION,
        help="version written to /ha/version (default: version.txt)",
    )
    parser.add_argument(
        "--channel",
        choices=CHANNEL_CHOICES,
        default="stable",
        help="update channel written to /ha/channel",
    )
    args = parser.parse_args(argv)
    if not valid_version(args.version):
        parser.error("--version must look like 1.2.3 or 1.2.3.4")
    unknown = [name for name in args.targets if name not in TARGETS]
    if unknown:
        parser.error("unknown target(s): " + ", ".join(unknown))
    names = selected_targets(args.targets)
    if args.check:
        return check_names(names, args.version, args.channel)
    return build(names, args.version, args.channel)


if __name__ == "__main__":
    raise SystemExit(main())
